package org.mz.mzfit.data

import org.mz.mzfit.data.Muscle.*

enum class Equipment(val displayName: String) {
    BODYWEIGHT("Bodyweight"), DUMBBELL("Dumbbell"), BARBELL("Barbell"), KETTLEBELL("Kettlebell"),
    CABLE("Cable"), MACHINE("Machine"), BAND("Band"), PULL_UP_BAR("Pull-up bar"), BENCH("Bench")
}

enum class Level(val displayName: String) { BEGINNER("Beginner"), INTERMEDIATE("Intermediate"), ADVANCED("Advanced") }

/**
 * Movement patterns the AI Coach can recognize from pose landmarks.
 * Each maps to a tracker spec in [org.mz.mzfit.ml.pose.TrackerSpecs].
 */
enum class MotionPattern(val cameraSetup: String) {
    SQUAT("Stand side-on (or at 45°) to the camera, 2–3 m away, head to feet in frame."),
    PUSH_UP("Place the phone at floor level, side-on to your body."),
    BICEP_CURL("Stand side-on or at 45° to the camera with your upper body and hips in frame."),
    SHOULDER_PRESS("Face the camera; keep your arms and hips in frame."),
    LUNGE("Stand side-on to the camera with your full body in frame."),
    GLUTE_BRIDGE("Lie side-on to the camera with the phone at floor level."),
    LATERAL_RAISE("Face the camera with both arms fully in frame."),
    HIP_HINGE("Stand side-on to the camera, full body in frame."),
    JUMPING_JACK("Face the camera, 2–3 m away, arms and feet in frame."),
    PLANK("Place the phone at floor level, side-on to your body."),
    SIT_UP("Lie side-on to the camera with the phone at floor level."),
    BENT_OVER_ROW("Stand side-on to the camera, full body in frame."),
    OVERHEAD_EXTENSION("Stand side-on to the camera with your arms in frame."),
}

data class Exercise(
    val id: String,
    val name: String,
    val bodyPart: BodyPart,
    val primary: List<Muscle>,
    val secondary: List<Muscle>,
    val equipment: Equipment,
    val level: Level,
    val steps: List<String>,
    val cues: List<String>,
    val pattern: MotionPattern? = null,
    val defaultSets: Int = 3,
    val defaultReps: Int = 10,
    /** Timed holds (e.g. plank) use seconds instead of reps. */
    val isHold: Boolean = false,
) {
    val isAiTracked: Boolean get() = pattern != null
    val allMuscles: List<Muscle> get() = primary + secondary
}

